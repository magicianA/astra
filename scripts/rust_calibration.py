"""Update the Rust output of the existing offline photometric calibrations."""

import math
import tempfile
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "rust/calibration.rs"


def _write(section, body, target):
    # The two calibrations run independently; preserve the other generated block.
    source = target.read_text()
    begin = f"// BEGIN GENERATED {section}\n"
    end = f"// END GENERATED {section}"
    if source.count(begin) != 1 or source.count(end) != 1:
        raise ValueError(f"Missing or duplicate {section} markers in {target}")
    before, _, rest = source.partition(begin)
    _, _, after = rest.partition(end)
    generated = before + begin + body + end + after
    with tempfile.NamedTemporaryFile(mode="w", dir=target.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(generated)
            stream.flush()
            temporary.chmod(target.stat().st_mode)
            temporary.replace(target)
        finally:
            temporary.unlink(missing_ok=True)


def write_background(scale, target=TARGET):
    if not math.isfinite(scale) or scale <= 0:
        raise ValueError("Background radiance scale must be finite and positive")
    _write(
        "BACKGROUND",
        "// Generated by scripts/prepare_background.py.\n"
        f"pub const BACKGROUND_RADIANCE_SCALE: f32 = {scale:.12f};\n",
        target,
    )


def write_twilight(values, lut_sha256, target=TARGET):
    values = list(values)
    if len(values) != 401 or not all(math.isfinite(value) for value in values):
        raise ValueError("Twilight calibration requires 401 finite values")
    if len(lut_sha256) != 64 or any(c not in "0123456789abcdef" for c in lut_sha256):
        raise ValueError("Invalid clear LUT SHA-256")
    _write(
        "TWILIGHT",
        "// Generated by scripts/calibrate_twilight.py.\n"
        "// Natural night is subtracted before fitting scattered solar light.\n"
        f"// Clear LUT SHA-256: {lut_sha256}\n"
        "pub const TWILIGHT_LOG_GAIN: [f64; 401] = [\n"
        + "".join(f"    {value:.12f},\n" for value in values)
        + "];\n",
        target,
    )
